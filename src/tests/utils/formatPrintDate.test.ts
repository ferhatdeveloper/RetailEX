import { describe, expect, it } from 'vitest';
import { buildDayEndZReportPrintHtml } from '../../utils/dayEndZReportPrint';
import {
  formatPrintDate,
  formatPrintDateRange,
  formatPrintDateTime,
  formatPrintTime,
} from '../../utils/dateLocale';

describe('formatPrintDate — 80mm fiş ve Z', () => {
  it('1 Kasım 2026 günü 01.11.2026', () => {
    expect(formatPrintDate(new Date(2026, 10, 1))).toBe('01.11.2026');
    expect(formatPrintDate('2026-11-01')).toBe('01.11.2026');
  });

  it('aralık 01.11.2026 - 03.11.2026, aynı gün tek tarih', () => {
    expect(formatPrintDateRange('2026-11-01', '2026-11-03')).toBe('01.11.2026 - 03.11.2026');
    expect(formatPrintDateRange('2026-11-01', '2026-11-01')).toBe('01.11.2026');
  });

  it('saat 12:11:03 kalır', () => {
    expect(formatPrintTime('2026-11-01T12:11:03')).toBe('12:11:03');
    expect(formatPrintDateTime('2026-11-01T12:11:03')).toBe('01.11.2026 12:11:03');
  });

  it('Z raporu HTML ay adı taşımaz', () => {
    const html = buildDayEndZReportPrintHtml({
      docTitle: 'Z REPORT',
      headerTitle: 'Z REPORT',
      storeSystem: 'EXFIN',
      dateCaption: 'Date',
      dateLabel: formatPrintDateRange('2026-11-01', '2026-11-03'),
      reportTimeCaption: 'Report time',
      reportTime: '12:11:03',
      txnCaption: 'Transaction count',
      txnCount: '0',
      grossCaption: 'Gross sales',
      grossSales: '0',
      discountCaption: 'Total discount',
      discount: '0',
      returnCaption: 'Sales return amount',
      salesReturn: '0',
      expenseCaption: 'Total Expense',
      expense: '0',
      netSalesCaption: 'Net sales amount',
      netSales: '0',
      reservationCaption: 'Reservation Amount',
      reservation: '50.0',
      netCashCaption: 'Net cash amount',
      netCash: '50.0',
      autoGenerated: 'This report was generated automatically.',
      versionLine: 'EXFIN',
    });
    expect(html).toContain('EXFIN');
    expect(html).not.toContain('RetailOS');
    expect(html).toContain('01.11.2026 - 03.11.2026');
    expect(html).toContain('12:11:03');
    expect(html).not.toContain('Kasım');
    expect(html).toContain('50.0');
  });
});
