import { describe, expect, it } from 'vitest';
import type { Sale } from '../../core/types/models';
import { buildDayEndZReportPrintHtml } from '../../utils/dayEndZReportPrint';
import { formatPrintDateRange, formatPrintTime } from '../../utils/dateLocale';
import { buildPosZReport } from '../../utils/posZReport';
import { buildCenteredFirmHeaderHtml } from '../../utils/printFirmHeader';
import { RECEIPT_80MM_DOCUMENT_CSS, RECEIPT_80MM_SLIP_CSS } from '../../utils/receipt80mmDocumentCss';
import { buildReceipt80mmPrintHtml } from '../../utils/receipt80mmPrintHtml';

const FIRM = 'Güneş Market';

function saleFixture(): Sale {
  return {
    id: 's1',
    receiptNumber: 'POS-1',
    date: '2026-11-01T19:43:56',
    customerName: 'Perakende Müşteri',
    items: [
      { productId: 'p1', productName: 'Ekmek', quantity: 1, price: 65_000, discount: 0, total: 65_000 },
    ],
    subtotal: 65_000,
    discount: 0,
    total: 65_000,
    paymentMethod: 'cash',
    cashier: 'Kasa',
  };
}

describe('80mm fiş yerleşimi', () => {
  it('ortak stil sabit boy kullanmaz, gövde siyah ve 13px', () => {
    const css = `${RECEIPT_80MM_DOCUMENT_CSS}\n${RECEIPT_80MM_SLIP_CSS}`;
    expect(css).toContain('size: 80mm auto');
    expect(css).toContain('margin: 0');
    expect(css).toContain('color: #000');
    expect(css).toContain('font-size: 13px');
    expect(css).toContain('font-weight: 500');
    expect(css).toContain('font-weight: 600');
    expect(css).toContain('line-height: 1.2');
    expect(css).toContain('min-height: 0');
    expect(css).toContain('max-height: 56px');
    expect(css).not.toMatch(/min-height:\s*100vh/);
    expect(css).not.toMatch(/80mm\s+297mm/);
    expect(css).not.toMatch(/min-height:\s*\d{3,}mm/);
  });

  it('fiş HTML firma adını taşır, tutarı korur ve uzun boş sayfa zorlamaz', () => {
    const html = buildReceipt80mmPrintHtml({
      sale: saleFixture(),
      paymentData: {
        payments: [{ method: 'cash', amount: 65_000, currency: 'IQD' }],
        totalPaid: 65_000,
        change: 0,
      },
      receiptSettings: { companyName: 'RetailOS Mağaza Sistemi' },
      companyNameFallback: 'Firma 001',
      firmTitle: FIRM,
      locale: 'tr',
    });
    expect(html).toContain('data-print-firm-name="1"');
    expect(html).toContain(FIRM);
    expect(html).toContain('65.000');
    expect(html).toContain('color: #000');
    expect(html).toContain('font-size: 13px');
    expect(html).not.toMatch(/min-height:\s*100vh/);
    expect(html).not.toMatch(/80mm\s+297mm/);
  });

  it('Z raporu tarihi 01.11.2026 - 03.11.2026, ay adı yok, tutar aynı', () => {
    const dateLabel = formatPrintDateRange('2026-11-01', '2026-11-03');
    const reportTime = formatPrintTime(new Date(2026, 10, 3, 12, 11, 3));
    expect(dateLabel).toBe('01.11.2026 - 03.11.2026');
    expect(reportTime).toBe('12:11:03');
    expect(buildPosZReport([], '2026-11-01').dateLabel).toBe('01.11.2026');
    const html = buildDayEndZReportPrintHtml({
      firmName: FIRM,
      docTitle: 'Z REPORT',
      headerTitle: 'Z REPORT',
      storeSystem: 'RetailOS Store System',
      dateCaption: 'Date',
      dateLabel,
      reportTimeCaption: 'Report time',
      reportTime,
      txnCaption: 'Transaction count',
      txnCount: '0',
      grossCaption: 'Gross sales',
      grossSales: '0',
      discountCaption: 'Total discount',
      discount: '0',
      returnCaption: 'Sales return amount',
      salesReturn: '0',
      expenseCaption: 'Total Expense',
      expense: '0',
      netSalesCaption: 'Net sales amount',
      netSales: '0',
      reservationCaption: 'Reservation Amount',
      reservation: '50.0',
      netCashCaption: 'Net cash amount',
      netCash: '50.0',
      autoGenerated: 'This report was generated automatically.',
      versionLine: 'RetailOS v1.0',
    });
    expect(html).toContain('01.11.2026 - 03.11.2026');
    expect(html).toContain('12:11:03');
    expect(html).not.toContain('Kasım');
    expect(html).toContain('>50.0<');
  });

  it('İngilizce POS fişinde tarih 01.11.2026 12:11:03', () => {
    const html = buildReceipt80mmPrintHtml({
      sale: { ...saleFixture(), date: '2026-11-01T12:11:03' },
      paymentData: {
        payments: [{ method: 'cash', amount: 65_000, currency: 'IQD' }],
        totalPaid: 65_000,
        change: 0,
      },
      receiptSettings: { companyName: 'RetailOS Mağaza Sistemi' },
      companyNameFallback: 'Firma 001',
      firmTitle: FIRM,
      locale: 'en',
    });
    expect(html).toContain('01.11.2026 12:11:03');
    expect(html).not.toContain('Kasım');
    expect(html).not.toContain('November');
    expect(html).toContain('65.000');
  });

  it('Z raporu aynı sıkı kabuğu ve firma başlığını kullanır', () => {
    const html = buildDayEndZReportPrintHtml({
      firmName: FIRM,
      docTitle: 'Z Raporu',
      headerTitle: 'Z RAPORU',
      storeSystem: 'Mağaza',
      dateCaption: 'Tarih',
      dateLabel: '1 Kasım 2026',
      reportTimeCaption: 'Rapor Saati',
      reportTime: '19:43:56',
      txnCaption: 'Toplam işlem sayısı',
      txnCount: '1',
      grossCaption: 'Brüt satış',
      grossSales: '65.000',
      discountCaption: 'Toplam İndirim',
      discount: '0',
      returnCaption: 'Satış iade tutarı',
      salesReturn: '0',
      expenseCaption: 'Toplam Gider',
      expense: '0',
      netSalesCaption: 'Net satış tutarı',
      netSales: '65.000',
      reservationCaption: 'Rezervasyon Tutarı',
      reservation: '50.000',
      netCashCaption: 'Net nakit tutarı',
      netCash: '115.000',
      autoGenerated: 'Bu rapor otomatik oluşturulmuştur',
      versionLine: 'RetailOS v1.0',
    });
    expect(html).toContain('data-print-firm-name="1"');
    expect(html).toContain(FIRM);
    expect(html).toContain('65.000');
    expect(html).toContain('115.000');
    expect(html).toContain('size: 80mm auto');
    expect(html).toContain('font-size: 13px');
    expect(html).not.toMatch(/min-height:\s*100vh/);
    expect(html).not.toContain('padding: 5mm');
  });

  it('logo yüksekliği rulo yemesin diye 56px ile sınırlı', () => {
    const html = buildCenteredFirmHeaderHtml({
      firmName: FIRM,
      logoDataUrl: 'data:image/png;base64,AAAA',
    });
    expect(html).toContain('max-height:56px');
    expect(html).toContain('data-print-firm-name="1"');
    expect(html).toContain('font-weight:600');
  });

  it('logo görseli blok ve yatayda otomatik kenarlı, başlık ortalı', () => {
    const css = `${RECEIPT_80MM_DOCUMENT_CSS}\n${RECEIPT_80MM_SLIP_CSS}`;
    const imgAt = css.indexOf('.rx-firm-logo img');
    expect(imgAt).toBeGreaterThan(-1);
    const imgRule = css.slice(imgAt, css.indexOf('}', imgAt));
    expect(imgRule).toContain('display: block');
    expect(imgRule).toContain('margin-left: auto');
    expect(imgRule).toContain('margin-right: auto');
    expect(imgRule).toContain('float: none');
    expect(css).toMatch(/\.rx-firm-header[\s\S]*?text-align:\s*center/);
    expect(RECEIPT_80MM_SLIP_CSS).toMatch(/\[data-section="header"\][\s\S]*?text-align:\s*center/);

    const html = buildCenteredFirmHeaderHtml({
      firmName: FIRM,
      logoDataUrl: 'data:image/png;base64,AAAA',
    });
    const logoAt = html.indexOf('data-print-firm-logo');
    const nameAt = html.indexOf('data-print-firm-name');
    expect(nameAt).toBeGreaterThan(logoAt);
    const imgTag = html.slice(html.indexOf('<img'), html.indexOf('/>', html.indexOf('<img')) + 2);
    expect(imgTag).toContain('display:block');
    expect(imgTag).toContain('margin-left:auto');
    expect(imgTag).toContain('margin-right:auto');
    expect(imgTag).toContain('float:none');
    expect(html).toContain('direction:ltr');
    expect(html.slice(0, logoAt)).toContain('text-align:center');
    expect(html).toContain('width:100%');
    expect(html).toContain('max-height:56px');
  });
});
