import { describe, expect, it } from 'vitest';
import type { Sale } from '../../core/types/models';
import { buildDayEndZReportPrintHtml } from '../../utils/dayEndZReportPrint';
import {
  buildCenteredFirmHeaderHtml,
  resolvePrintFirmName,
} from '../../utils/printFirmHeader';
import { buildReceipt80mmPrintHtml } from '../../utils/receipt80mmPrintHtml';

const LOGO = 'data:image/png;base64,AAAA';
const FIRM = 'Güneş Market';
const PRODUCT = 'RetailOS Mağaza Sistemi';

describe('yazdırma firma başlığı', () => {
  it('yer tutucu ve ürün satırı gerçek firma adını ezmez', () => {
    expect(
      resolvePrintFirmName({
        receiptCompanyName: PRODUCT,
        name: 'Firma 001',
        title: FIRM,
      }),
    ).toBe(FIRM);
  });

  it('logo yoksa firma adı başlık yerinde ortalanır', () => {
    const html = buildCenteredFirmHeaderHtml({ firmName: FIRM });
    expect(html.includes('<img')).toBe(false);
    expect(html).toContain(FIRM);
    expect(html).toContain('text-align:center');
    expect(html).toContain('data-print-firm-name="1"');
    expect(html.includes(PRODUCT)).toBe(false);
  });

  it('firma adı logonun altında ve ortalıdır', () => {
    const html = buildCenteredFirmHeaderHtml({ firmName: FIRM, logoDataUrl: LOGO });
    const logoAt = html.indexOf('data-print-firm-logo');
    const nameAt = html.indexOf('data-print-firm-name');
    expect(logoAt).toBeGreaterThan(-1);
    expect(nameAt).toBeGreaterThan(logoAt);
    expect(html).toContain(FIRM);
    expect(html).toContain('text-align:center');
    expect(html.includes(PRODUCT)).toBe(false);
  });
});

describe('Z raporu yazdırma başlığı', () => {
  it('firma adı logonun altında kalır, ürün alt satırı ve tutarlar durur', () => {
    const html = buildDayEndZReportPrintHtml({
      firmName: FIRM,
      logoDataUrl: LOGO,
      docTitle: 'Z Raporu',
      headerTitle: 'Z RAPORU',
      storeSystem: 'EXFIN',
      dateCaption: 'Tarih',
      dateLabel: '1 Kasım 2026 Pazar',
      reportTimeCaption: 'Rapor Saati',
      reportTime: '19:43:56',
      txnCaption: 'Toplam işlem sayısı',
      txnCount: '1',
      grossCaption: 'Brüt satış',
      grossSales: '65.000',
      discountCaption: 'Toplam İndirim',
      discount: '0',
      returnCaption: 'Satış iade tutarı',
      salesReturn: '0',
      expenseCaption: 'Toplam Gider',
      expense: '0',
      netSalesCaption: 'Net satış tutarı',
      netSales: '65.000',
      reservationCaption: 'Rezervasyon Tutarı',
      reservation: '50.000',
      netCashCaption: 'Net nakit tutarı',
      netCash: '115.000',
      autoGenerated: 'Bu rapor otomatik oluşturulmuştur',
      versionLine: 'EXFIN',
    });
    const logoAt = html.indexOf('data-print-firm-logo');
    const nameAt = html.indexOf(`data-print-firm-name`);
    const titleAt = html.indexOf('Z RAPORU');
    const productAt = html.indexOf('EXFIN');
    expect(logoAt).toBeGreaterThan(-1);
    expect(nameAt).toBeGreaterThan(logoAt);
    expect(titleAt).toBeGreaterThan(nameAt);
    expect(productAt).toBeGreaterThan(titleAt);
    expect(html).toContain('EXFIN');
    expect(html).not.toContain('RetailOS');
    expect(html).toContain(FIRM);
    expect(html).toContain('65.000');
    expect(html).toContain('50.000');
    expect(html).toContain('115.000');
    expect(html.slice(nameAt, nameAt + 180).includes(PRODUCT)).toBe(false);
    expect(html.slice(nameAt, nameAt + 180).includes('EXFIN')).toBe(false);
  });
});

describe('fiş yazdırma başlığı', () => {
  it('ortak fiş başlığında firma adı logonun altındadır', () => {
    const sale: Sale = {
      id: 's1',
      receiptNumber: 'POS-1',
      date: '2026-11-01T19:43:56',
      customerName: 'Perakende Müşteri',
      items: [
        { productId: 'p1', productName: 'Ekmek', quantity: 1, price: 65_000, discount: 0, total: 65_000 },
      ],
      subtotal: 65_000,
      discount: 0,
      total: 65_000,
      paymentMethod: 'cash',
      cashier: 'Kasa',
    };
    const html = buildReceipt80mmPrintHtml({
      sale,
      paymentData: {
        payments: [{ method: 'cash', amount: 65_000, currency: 'IQD' }],
        totalPaid: 65_000,
        change: 0,
      },
      receiptSettings: {
        companyName: PRODUCT,
        logoDataUrl: LOGO,
      },
      companyNameFallback: 'Firma 001',
      firmTitle: FIRM,
      locale: 'tr',
    });
    const logoAt = html.indexOf('data-print-firm-logo');
    const nameAt = html.indexOf('data-print-firm-name');
    expect(logoAt).toBeGreaterThan(-1);
    expect(nameAt).toBeGreaterThan(logoAt);
    expect(html).toContain(FIRM);
    const nameSlice = html.slice(nameAt, html.indexOf('</div>', nameAt));
    expect(nameSlice.includes(PRODUCT)).toBe(false);
    expect(nameSlice.includes('Firma 001')).toBe(false);
  });
});
