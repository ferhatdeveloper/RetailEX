/**
 * Gün sonu Z yazdırma gövdesi. Tutarlar çağıran tarafta formatlanır; burada hesap yok.
 */
import { buildCenteredFirmHeaderHtml, escapePrintHtml } from './printFirmHeader';

export type DayEndZReportPrintInput = {
  firmName?: string | null;
  logoDataUrl?: string | null;
  docTitle: string;
  headerTitle: string;
  storeSystem: string;
  dateCaption: string;
  dateLabel: string;
  reportTimeCaption: string;
  reportTime: string;
  txnCaption: string;
  txnCount: string;
  grossCaption: string;
  grossSales: string;
  discountCaption: string;
  discount: string;
  returnCaption: string;
  salesReturn: string;
  expenseCaption: string;
  expense: string;
  netSalesCaption: string;
  netSales: string;
  reservationCaption: string;
  reservation: string;
  netCashCaption: string;
  netCash: string;
  restaurantProductsHtml?: string;
  autoGenerated: string;
  versionLine: string;
};

export function buildDayEndZReportPrintHtml(input: DayEndZReportPrintInput): string {
  const esc = escapePrintHtml;
  const firmHeaderHtml = buildCenteredFirmHeaderHtml({
    firmName: input.firmName,
    logoDataUrl: input.logoDataUrl,
    nameStyle: 'text-align:center;font-weight:700;margin-top:1mm',
  });

  return `
      <!DOCTYPE html>
      <html>
      <head>
        <meta charset="UTF-8">
        <title>${esc(input.docTitle)} - ${esc(input.dateLabel)}</title>
        <style>
          html {
            width: 80mm;
            max-width: 80mm;
            margin: 0;
            padding: 0;
          }
          @media print {
            @page { size: 80mm auto; margin: 0; }
            html, body {
              width: 80mm !important;
              max-width: 80mm !important;
              margin: 0 !important;
            }
          }
          body {
            box-sizing: border-box;
            width: 100%;
            max-width: 80mm;
            font-family: 'Courier New', monospace;
            font-size: 11px;
            line-height: 1.3;
            padding: 5mm;
            margin: 0;
            color: #000;
            text-align: left;
          }
          .center { text-align: center; }
          .bold { font-weight: bold; }
          .large { font-size: 14px; }
          .divider { border-top: 1px dashed #000; margin: 3mm 0; }
          .row { display: flex; justify-content: space-between; margin: 1mm 0; }
          .row .label { color: #111; }
          .row .value { font-weight: 700; }
          .header { margin-bottom: 3mm; }
          .small { font-size: 9px; color: #444; }
          .section-title { text-align: center; font-weight: 700; margin: 1mm 0 2mm; }
          .deduct { color: #b91c1c; }
          .final { border-top: 1px solid #000; padding-top: 1.2mm; margin-top: 1.2mm; font-size: 13px; font-weight: 700; }
        </style>
      </head>
      <body>
        <div class="header center">
          ${firmHeaderHtml}
          <div class="bold large">${esc(input.headerTitle)}</div>
          <div>${esc(input.storeSystem)}</div>
        </div>
        
        <div class="divider"></div>
        
        <div class="row">
          <span>${esc(input.dateCaption)}:</span>
          <span class="bold">${esc(input.dateLabel)}</span>
        </div>
        <div class="row">
          <span>${esc(input.reportTimeCaption)}:</span>
          <span>${esc(input.reportTime)}</span>
        </div>
        
        <div class="divider"></div>
        
        <div class="row">
          <span class="label">${esc(input.txnCaption)}</span>
          <span class="value">${esc(input.txnCount)}</span>
        </div>
        <div class="row">
          <span class="label">${esc(input.grossCaption)}</span>
          <span class="value">${esc(input.grossSales)}</span>
        </div>
        <div class="row">
          <span class="label">${esc(input.discountCaption)}</span>
          <span>${esc(input.discount)}</span>
        </div>
        <div class="row">
          <span class="label">${esc(input.returnCaption)}</span>
          <span class="deduct">${esc(input.salesReturn)}</span>
        </div>
        <div class="row">
          <span class="label">${esc(input.expenseCaption)}</span>
          <span class="deduct">${esc(input.expense)}</span>
        </div>
        <div class="row final">
          <span class="label">${esc(input.netSalesCaption)}</span>
          <span>${esc(input.netSales)}</span>
        </div>
        <div class="row">
          <span class="label">${esc(input.reservationCaption)}</span>
          <span>${esc(input.reservation)}</span>
        </div>
        <div class="row final">
          <span class="label">${esc(input.netCashCaption)}</span>
          <span>${esc(input.netCash)}</span>
        </div>
        ${input.restaurantProductsHtml || ''}
        <div class="divider"></div>
        
        <div class="center" style="margin-top: 5mm; font-size: 10px;">
          <div>${esc(input.autoGenerated)}</div>
          <div>${esc(input.versionLine)}</div>
        </div>
      </body>
      </html>
    `;
}
